TEST(JpegProgressive, DecodesToGrayscaleWithoutFaulting) {
  JPEGDEC jpeg;
  ASSERT_TRUE(jpeg.openRAM(const_cast<uint8_t*>(kProgressiveJpeg), static_cast<int>(sizeof(kProgressiveJpeg)),
                           discardRows))
      << "fixture is not a JPEG this build can open";

  ASSERT_EQ(jpeg.getJPEGType(), JPEG_MODE_PROGRESSIVE) << "fixture stopped being progressive; the guard is void";
  EXPECT_EQ(jpeg.getWidth(), 96);
  EXPECT_EQ(jpeg.getHeight(), 96);

  // Both of these matter. Grayscale is what makes Cb and Cr skip, and
  // JPEGDEC forces progressive streams to eighth scale internally anyway.
  jpeg.setPixelType(EIGHT_BIT_GRAYSCALE);

  // An unpatched JPEGDEC does not fail here. It dies.
  const int rc = jpeg.decode(0, 0, JPEG_SCALE_EIGHTH);
  EXPECT_EQ(rc, 1) << "decode returned failure, error " << jpeg.getLastError();
  EXPECT_EQ(jpeg.getLastError(), JPEG_SUCCESS);

  jpeg.close();
}
