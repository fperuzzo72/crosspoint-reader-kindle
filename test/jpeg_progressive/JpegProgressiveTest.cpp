// A progressive, 3-component JPEG must decode to grayscale without faulting.
//
// This is a regression guard for a bug that was NOT in this repository's code:
// JPEGDEC's own JPEGDecodeMCU_P computes
//
//     signed short *pMCU = &pJPEG->sMCUs[iMCU & 0xffffff];
//
// and in MCU_SKIP iMCU arrives negative, so the mask produces a pointer about
// 33 MB past sMCUs. The first AC coefficient write store-faults. It needs a
// progressive 3-component stream decoded to grayscale, because each Y MCU
// drags two MCU_SKIP calls behind it for Cb and Cr, which is exactly what the
// reader does with every progressive image in a book.
//
// scripts/jpegdec_patches/ has carried the fix all along and nothing applied
// it: patch_jpegdec.py is a PlatformIO pre-build step, and this port builds
// through tools/kindle/, which never goes near PlatformIO. The source was
// right and the binary was wrong, which is why nobody found it by reading
// code. tools/kindle/fetch-deps.sh applies the patches now.
//
// Found by reading a book: the first spine item with an image killed the
// process, and every figure in it was progressive. The fixture below is a
// gradient rather than that figure, so no book's copyright travels with the
// test and the input is small enough to read.
//
// So this test exists to catch the DEPENDENCY regressing, not the tree: a
// refetch that misses the patch step fails here rather than on a device, in
// the middle of a book, with a process that vanishes.
//
// The fixture is synthetic on purpose, 96x96 of arithmetic gradient, small
// enough to read and free of anyone's copyright. It reproduces the fault
// exactly: unpatched the process dies with SIGSEGV, patched it decodes.

